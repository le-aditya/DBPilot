"""Exports. PRD F10.

Results go out as CSV or JSON; the schema goes out as Markdown, generated from
the same introspection service that feeds the explorer and the ER diagram, so
the documentation cannot drift away from what the database actually contains.
"""

import csv
import io
import json
from collections.abc import Iterator, Sequence
from typing import Any

from app.services.introspection import TableDescription

CHUNK_ROWS = 500


def _cell(value: Any) -> Any:
    if value is None or isinstance(value, bool | int | float | str):
        return value
    return str(value)


def rows_to_csv(columns: Sequence[str], rows: Sequence[Sequence[Any]]) -> Iterator[str]:
    """Stream CSV, so a large export never becomes one large string in memory."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(columns)

    for index, row in enumerate(rows, start=1):
        writer.writerow(["" if cell is None else _cell(cell) for cell in row])
        if index % CHUNK_ROWS == 0:
            yield buffer.getvalue()
            buffer.seek(0)
            buffer.truncate(0)

    remaining = buffer.getvalue()
    if remaining:
        yield remaining


def rows_to_json(columns: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    """Objects keyed by column name, which is what a consumer actually wants."""
    return json.dumps(
        [{column: _cell(value) for column, value in zip(columns, row, strict=False)}
         for row in rows],
        indent=2,
        default=str,
    )


def _escape(text: str) -> str:
    return text.replace("|", "\\|")


def schema_to_markdown(project_name: str, tables: Sequence[TableDescription]) -> str:
    """Schema documentation. PRD F10 notes this doubles as the design write-up."""
    lines = [
        f"# {project_name} — schema",
        "",
        f"{len(tables)} tables. Generated by DBPilot from the live database.",
        "",
    ]

    if not tables:
        lines.append("_This project has no tables yet._")
        return "\n".join(lines) + "\n"

    lines += ["## Contents", ""]
    for table in tables:
        lines.append(f"- [{table.name}](#{table.name}) — {table.row_count} rows")
    lines.append("")

    for table in tables:
        lines += [
            f"## {table.name}",
            "",
            f"{table.row_count} rows, {len(table.columns)} columns.",
            "",
            "| Column | Type | Nullable | Key | Default |",
            "| --- | --- | --- | --- | --- |",
        ]
        for column in table.columns:
            marks = []
            if column.is_primary_key:
                marks.append("PK")
            if column.references_table:
                marks.append(f"FK → {column.references_table}.{column.references_column}")
            lines.append(
                f"| `{column.name}` | `{column.data_type}` "
                f"| {'yes' if column.nullable else 'no'} "
                f"| {_escape(', '.join(marks)) or '—'} "
                f"| {f'`{_escape(column.default)}`' if column.default else '—'} |"
            )
        lines.append("")

        if table.indexes:
            lines += ["**Indexes**", ""]
            for index in table.indexes:
                lines.append(f"- `{index.name}` — `{_escape(index.definition)}`")
            lines.append("")

    relationships = [
        (table.name, column)
        for table in tables
        for column in table.columns
        if column.references_table
    ]
    if relationships:
        lines += [
            "## Relationships",
            "",
            "| From | To |",
            "| --- | --- |",
        ]
        for name, column in relationships:
            lines.append(
                f"| `{name}.{column.name}` "
                f"| `{column.references_table}.{column.references_column}` |"
            )
        lines.append("")

    return "\n".join(lines)
